/**
 * Renders the booth's vintage collage to static markup for the phone pages, which are
 * plain HTML route handlers and can't import react-dom/server. Runs before every build.
 */
import { writeFileSync } from "node:fs";
import { renderToStaticMarkup } from "react-dom/server";
import Collage from "../src/components/Collage";

const html = renderToStaticMarkup(
  <Collage />,
);

writeFileSync(
  new URL("../src/lib/server/scenery-html.ts", import.meta.url),
  `// Generated by scripts/gen-scenery.tsx from src/components/Collage.tsx. Do not edit.\nexport const SCENERY_HTML = ${JSON.stringify(html)};\n`,
);
console.log(`scenery-html.ts: ${(html.length / 1024).toFixed(1)} KB`);
