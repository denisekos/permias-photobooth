/**
 * Renders the booth's paper-cut scenery to static markup for the phone pages, which are
 * plain HTML route handlers and can't import react-dom/server. Runs before every build.
 */
import { writeFileSync } from "node:fs";
import { renderToStaticMarkup } from "react-dom/server";
import Scenery, { SceneryDefs } from "../src/components/Scenery";

const html = renderToStaticMarkup(
  <>
    <SceneryDefs />
    <Scenery variant="page" />
  </>,
);

writeFileSync(
  new URL("../src/lib/server/scenery-html.ts", import.meta.url),
  `// Generated by scripts/gen-scenery.tsx from src/components/Scenery.tsx. Do not edit.\nexport const SCENERY_HTML = ${JSON.stringify(html)};\n`,
);
console.log(`scenery-html.ts: ${(html.length / 1024).toFixed(1)} KB`);
